import re
from loguru import logger

from llm import chat_completion

# Один запрос делает и перевод, и суммаризацию сразу — при дневном лимите
# бесплатных запросов на OpenRouter два отдельных вызова на статью съели бы
# бюджет вдвое быстрее. Модель сама решает, нужен ли перевод (для Habr — нет).
#
# Системный промпт с требованием "только русский" вынесен отдельно и
# продублирован в пользовательском — на реальных прогонах модель (особенно
# MoE вроде nemotron) иногда оставляла отдельные слова/фразы непереведёнными
# ("exposing PII", "bipartisan") или роняла случайный иероглиф — одного
# упоминания в промпте оказалось недостаточно.
SYSTEM_PROMPT = (
    "Ты — редактор технического Telegram-канала. Отвечай ТОЛЬКО на русском "
    "языке: каждое слово должно быть русским. Переводи вообще всё, включая "
    "термины и фразы вроде 'bipartisan' или 'exposing PII' — не оставляй их "
    "на английском или любом другом языке. Названия продуктов, компаний и "
    "брендов (ChatGPT, GitHub, Boston Dynamics) можно оставлять как есть."
)

PROMPT = (
    "Тебе дан заголовок и текст статьи (на русском или английском языке).\n"
    "Ответь строго в формате из семи полей:\n"
    "Заголовок: <заголовок на русском, не длиннее 100 символов>\n"
    "Текст: <выжимка на русском, 3-5 предложений, только факты, без вводных "
    "фраз вроде «в статье говорится»>\n"
    "Теги: <2-3 коротких хэштега по теме статьи на русском, каждый одним "
    "словом, без решётки, через запятую, например: нейросети, технологии>\n"
    "Картинка: <краткое описание на английском для иллюстрации, 5-10 слов, "
    "конкретная сцена или объект, который можно нарисовать — не абстрактные "
    "понятия вроде 'separation of concerns' или 'data privacy'>\n"
    "Почему важно: <одно предложение на русском: что новость меняет для "
    "читателя — что теперь можно или нельзя, кому это грозит, на что смотреть. "
    "Не пиши общее «это важно для индустрии»>\n"
    "Вопрос: <вопрос подписчикам по теме статьи на русском, до 90 символов, "
    "такой, чтобы ответ был одним из вариантов ниже>\n"
    "Ответы: <2-3 коротких варианта ответа на русском, каждый не длиннее 25 "
    "символов, разделитель — вертикальная черта «|», без нумерации>\n\n"
    "Если оригинал уже на русском — не переводи дословно, а сократи своими словами.\n"
    "Напоминание: поля «Заголовок», «Текст», «Теги», «Почему важно», «Вопрос» "
    "и «Ответы» должны быть полностью на русском языке, без единого слова на "
    "английском или другом языке (кроме имён собственных). Поле «Картинка» — "
    "всегда на английском.\n\n"
)

# Редакторские поля («Почему важно», «Вопрос», «Ответы») стоят в промпте
# последними намеренно: если модель упрётся в max_tokens, обрежется хвост, то
# есть необязательные поля, а не заголовок с выжимкой. И разбираются они
# отдельными regex'ами, а не через RESPONSE_RE, по той же причине: RESPONSE_RE
# — «всё или ничего», и добавление новых полей в него означало бы, что модель,
# забывшая «Почему важно», теряет пост целиком.
FIELD_LABELS_RE = r'(?:Заголовок|Текст|Тег\S*|Карт\S*|Почему\s+важно|Вопрос|Ответ\S*)'

# Нумерация и маркеры списка, которые free-модель любит добавлять к вариантам
# ответа («1. Да», «- Нет»), хотя просили просто «Да | Нет».
OPTION_MARKER_RE = re.compile(r'^\s*(?:\d+[.)]|[-–—•*])\s*')

# Разделители вариантов: «|» (просили в промпте), перенос строки и «;» —
# модель может выбрать любой. Запятая в этот список не входит намеренно:
# «Да, заметно» — это ОДИН вариант, и разбивка по запятым превратила бы его
# в два бессмысленных. Запятыми режем только если других разделителей нет.
OPTION_SEPARATORS_RE = re.compile(r'[|\n;]+')


def _optional_field(content, label):
    """Значение необязательного поля («Почему важно:», «Вопрос:» и т.п.).
    Пустая строка, если модель его не написала или написала криво: пост без
    редакторского блока — нормальный пост, а не повод пропускать новость."""
    match = re.search(
        label + r'\s*:\s*(?P<value>.+?)(?=\s*' + FIELD_LABELS_RE + r'\s*:|\Z)',
        content,
        re.DOTALL,
    )
    return match.group('value').strip() if match else ''


def _parse_options(raw, limit=4):
    """Варианты ответа для опроса: режет по «|», переносам и «;», снимает
    нумерацию, отбрасывает пустое и дубли. Меньше двух вариантов — не ошибка
    разбора, а сигнал «опрос не публикуем» (проверяет вызывающий)."""
    raw = (raw or '').strip()
    if not raw:
        return []
    chunks = OPTION_SEPARATORS_RE.split(raw)
    if len(chunks) < 2:
        # Модель проигнорировала разделитель и написала «Да, Нет, Не знаю».
        chunks = raw.split(',')
    options = []
    for chunk in chunks:
        option = OPTION_MARKER_RE.sub('', chunk).strip().strip('«»"\'` ')
        if option and option not in options:
            options.append(option)
        if len(options) >= limit:
            break
    return options


# \s* вместо \s*\n+\s* между полями: вживую модель иногда пишет "Картинка:"
# в той же строке, сразу после текста выжимки, без переноса — с обязательным
# \n+ такие ответы (примерно половина!) не матчились и терялись зря.
# "Карт\S*:" вместо "Картинка:" — вживую модель один раз выдала "Картинka"
# (кириллическая "Карт" + латинские "k"/"a" на конце — визуально то же
# слово, разные code point'ы). Отдельная просьба писать чисто на русском
# в промпте это не исправила, поэтому парсинг сделан терпимым к концовке слова.
# Хвост "Картинки" ограничен началом следующего поля (с 11.2026 после неё идут
# «Почему важно»/«Вопрос»/«Ответы»): без этого жадный `.+` при DOTALL затягивал
# в промпт картинки весь опрос, и сток искался по мусорному запросу.
RESPONSE_RE = re.compile(
    r'Заголовок:\s*(?P<title>.+?)\s*'
    r'Текст:\s*(?P<summary>.+?)\s*'
    r'(?:Тег\S*:\s*(?P<tags>.+?)\s*)?'
    r'Карт\S*:\s*(?P<image_prompt>.+?)'
    r'(?=\s*(?:Почему\s+важно|Вопрос|Ответ\S*)\s*:|\Z)',
    re.DOTALL,
)

# Абзацы делаем сами, а не просьбой в промпте: модель инструкцию про "раздели
# пустой строкой" вживую игнорировала в 100% прогонов (см. журнал коммитов) —
# детерминированная группировка по предложениям надёжнее, чем ещё одна
# просьба к вероятностной модели.
SENTENCE_SPLIT_RE = re.compile(r'(?<=[.!?])\s+(?=[А-ЯA-Z])')


def split_into_paragraphs(text, sentences_per_paragraph=2):
    text = re.sub(r'\s+', ' ', text).strip()
    sentences = [s for s in SENTENCE_SPLIT_RE.split(text) if s]
    paragraphs = [
        ' '.join(sentences[i:i + sentences_per_paragraph])
        for i in range(0, len(sentences), sentences_per_paragraph)
    ]
    return '\n\n'.join(paragraphs)


def process_article(title, text):
    """Возвращает словарь с готовыми полями поста:

    ``title``, ``summary`` (с абзацами), ``image_prompt``, ``tags``,
    ``why`` (одно предложение «почему это важно»), ``poll_question`` и
    ``poll_options`` (список строк, может быть пустым).

    Словарь, а не кортеж из семи значений: половина полей необязательные, и
    распаковка `a, b, c, d, e, f, g` на глазах у читателя превращается в
    загадку. При любой ошибке — пустой словарь, чтобы вызывающий код просто
    пропустил статью, а не упал."""
    if not text:
        return {}

    try:
        # Собираем текст запроса конкатенацией, а не через str.format: текст
        # статьи (а иногда и заголовок) может содержать фигурные скобки — код,
        # JSON, C++-шаблоны. .format(...) на такой строке бросил бы KeyError
        # и уронил весь прогон; конкатенация скобки не трогает. Сборка тоже
        # внутри try, чтобы любая ошибка не вылетела за обработчик.
        user_content = (
            PROMPT
            + "\nЗаголовок статьи: " + title
            + "\n\nТекст статьи:\n" + text
        )
        content = chat_completion(
            [
                {'role': 'system', 'content': SYSTEM_PROMPT},
                {'role': 'user', 'content': user_content},
            ],
            temperature=0.3,
            max_tokens=600,
            task='суммаризация статьи',
        )
    except Exception as e:
        logger.error(f"Ошибка подготовки запроса к OpenRouter: {e}")
        return {}

    # Пустой ответ означает, что ни одна модель не ответила (причину
    # chat_completion уже залогировал) — статью пропускаем.
    if not content:
        return {}

    match = RESPONSE_RE.search(content)
    if not match:
        # Раньше здесь публиковался content как есть "лишь бы не терять
        # статью" — но вживую это пропустило в канал деградировавший ответ
        # модели (повторяющиеся <unk> и мусорные токены). Пропуск статьи —
        # намного дешевле, чем мусор в публичном канале.
        logger.warning(f"Ответ модели не в ожидаемом формате, пропускаю статью: {content[:200]!r}")
        return {}

    return {
        'title': match.group('title').strip(),
        'summary': split_into_paragraphs(match.group('summary').strip()),
        'image_prompt': match.group('image_prompt').strip(),
        'tags': match.group('tags').strip() if match.group('tags') else '',
        'why': _optional_field(content, r'Почему\s+важно'),
        'poll_question': _optional_field(content, r'Вопрос'),
        'poll_options': _parse_options(_optional_field(content, r'Ответ\S*')),
    }
